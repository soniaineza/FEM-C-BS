// Embeds assets/models/cars/*.glb into components/map/carModelData.ts as
// base64, so the map engine (a DOM component: WebView on Android, DOM on
// web) gets the models from its own bundle with no asset loading.
//   node scripts/build-car-models.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const dir = path.join(root, 'assets/models/cars');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.glb')).sort();
const lines = files.map((f) => {
  const b64 = fs.readFileSync(path.join(dir, f)).toString('base64');
  return `  ${JSON.stringify(path.basename(f, '.glb'))}: ${JSON.stringify(b64)},`;
});
const out = `// GENERATED by scripts/build-car-models.mjs from assets/models/cars/*.glb
// (Kenney "Car Kit", CC0). Do not edit by hand.
export const CAR_MODEL_GLB_BASE64: Record<string, string> = {
${lines.join('\n')}
};
`;
fs.writeFileSync(path.join(root, 'components/map/carModelData.ts'), out);
console.log(`embedded ${files.length} models (${(out.length / 1024).toFixed(0)} KB)`);
