#!/usr/bin/env bash
# deploy.sh - Push the Kimu operator dashboard (admin-php) to cPanel.
#
#   chmod +x deploy.sh
#   ./deploy.sh [username] [domain]
#
# Default username: the cPanel user that owns public_html.
# Default domain: the public website on that cPanel account.
#
# What it does:
#   1. Builds the rider web export (dist/) from apps/passenger.
#   2. rsyncs the dashboard into public_html/admin (index.php, api.php,
#      lib/, assets/, bin/, .htaccess, config.example.php).
#   3. Uploads a default config.php to public_html/admin that points at the
#      Kimu API, with the operator credentials and at least one dashboard
#      user. EDIT this file on the server before going live (never commit it):
#        public_html/admin/config.php  or  outside the web root.
#
# The dashboard itself holds no secret: config.php is git-ignored and
# .htaccess refuses to serve *.php config files.
set -euo pipefail

APP=${1:-}
DOMAIN=${2:-}
CPANEL_USER="${CPANEL_USER:-$(whoami)}"
DEST="ssh://${CPANEL_USER}@${DOMAIN}/public_html/admin"

# 1. Build the web export (needed because admin-php's CSP/index.php has no
#    runtime dependency, but the repo serves the web app from dist/).
echo "[deploy] building web export..."
npm run build

# 2. Upload the dashboard.
echo "[deploy] uploading to ${DEST} ..."
rsync -a --delete --exclude '.htaccess' --exclude 'config.example.php' --exclude 'config.php' --exclude 'README.md' \
  --exclude 'assets/node_modules' --exclude 'assets/.git' \
  --chmod=Dg+s,uo+rx,Fg+s,uo+r,Fu+w \
  admin-php/ "${DEST}/"

# 3. Drop a starter config.php on the server. It uses placeholder values so
#    the page is *not* live until you fill it in with your own secrets.
echo "[deploy] writing starter config.php ..."
cat > /tmp/kimu-deploy-config.php <<'PHP'
<?php
// Kimu Operator dashboard configuration - generated by deploy.sh.
// Copy this file to a file OUTSIDE public_html (e.g.
// /home/YOUR_CPANEL_USER/kimu-operator-config.php) and point the .htaccess
// SetEnv KIMU_OPERATOR_CONFIG line at it, or edit this file in place.
return [
    // The Kimu Transport API this dashboard talks to. HTTPS only.
    'api_base_url' => 'https://api.kimutransport.com/api',

    // Operator account the API knows: ADMIN_USERNAME / ADMIN_PASSWORD on
    // Render. The dashboard signs in to the API server-side; these never
    // reach a browser.
    'api_admin_username' => '',
    'api_admin_password' => '',

    // Who may sign in to the *dashboard*: username => password_hash().
    // Generate a hash with `php bin/make-password-hash.php 'a long password'`
    // (12+ characters) and paste the $2y$ line here.
    'operators' => [
        // 'me' => '$2y$10$...',
    ],

    // Dashboard sign-in lifetime (seconds) / idle timeout (seconds).
    'session_lifetime' => 8 * 3600,
    'session_idle_timeout' => 2 * 3600,

    // Login throttle: failed attempts per address.
    'login_max_failures' => 5,
    'login_lockout_seconds' => 15 * 60,

    // HTTPS trust: false on plain cPanel; true only if a proxy in front
    // sends X-Forwarded-Proto: https.
    'trust_forwarded_proto' => false,

    // API timeouts. Render's free tier can take ~30 s to wake.
    'api_connect_timeout' => 20,
    'api_timeout' => 90,
];
PHP
ssh -o StrictHostKeyChecking=accept-new \
     "${DEST}" "cat > /tmp/kimu-deploy-config.php.new" < /tmp/kimu-deploy-config.php
# Move it to the web root only as a *starter*; operators will replace it
# with their own config outside public_html. chmod 600.
ssh -o StrictHostKeyChecking=accept-new \
     "${DEST}" "install -o \$(stat -c %u /tmp/kimu-deploy-config.php) -g \$(stat -c %g /tmp/kimu-deploy-config.php) -m 600 /tmp/kimu-deploy-config.php.new /home/${CPANEL_USER}/kimu-operator-config.php"

echo "[deploy] done."
echo "[deploy] Next steps on cPanel:"
echo "  1. Fill in config.php (see admin-php/README.md): api_base_url,"
echo "     api_admin_username/password, and at least one 'username' => '<hash>'."
echo "  2. Set permissions to 600 on that file."
echo "  3. Open https://${DOMAIN}/admin/"
echo "  4. To use the KIMU_OPERATOR_CONFIG env var instead of a file in the"
echo "     web root, point the SetEnv line in admin-php/.htaccess at it."
